FoodCatalogCompanion _food({
  required String id,
  required String name,
  required String hindiName,
  required String category,
  required String defaultBasis,
  required double yieldFactor,
  required double kcal,
  required double protein,
  required double carbs,
  required double fat,
  double fibre = 0.0,
  double? satFat,
  double? sugar,
  double? sodiumMg,
  required double servingG,
  required String servingLabel,
}) {
  return FoodCatalogCompanion(
    id: Value(id),
    name: Value(name),
    hindiName: Value(hindiName),
    category: Value(category),
    source: const Value('ifct_2017'),
    defaultBasis: Value(defaultBasis),
    yieldFactor: Value(yieldFactor),
    kcalPer100g: Value(kcal),
    proteinPer100g: Value(protein),
    carbsPer100g: Value(carbs),
    fatPer100g: Value(fat),
    fibrePer100g: Value(fibre),
    saturatedFatPer100g: Value(satFat),
    sugarPer100g: Value(sugar),
    sodiumMgPer100g: Value(sodiumMg),
    defaultServingG: Value(servingG),
    servingLabel: Value(servingLabel),
  );
}
